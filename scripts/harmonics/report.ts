/**
 * The Markdown report (docs/reports/harmonic-interest.md) from an evaluation and its
 * summary: generated tables, highlights and problem lists, plus hand-written commentary
 * from commentary.md (sections `<!-- @name -->`), which was written against the default
 * configuration. Deterministic: no dates or timings.
 */
import commentaryText from './commentary.md?raw';
import { flagsOf, summarizeSeed } from './aggregate';
import { barChart, trajectoryPanels } from './charts';
import { APP_DEFAULTS, type BatchResult, type EvalOutput } from './evaluate';
import { DUP_LSD_DB, FORMANT_PROMINENCE_DB, K, LSD_FLOOR_DB, PHASE_ONLY_REL, PITCH_DB, SIG_DB } from './metrics';
import { DEFAULT_WEIGHTS } from './score';
import { seedSettings, type Summary } from './summary';

export interface Report {
  md: string;
  /** Extra files (path relative to the report's directory → content). */
  files: Record<string, string>;
}

const DATA_DIR = 'harmonic-interest-data';

const f = (v: number | null | undefined, d = 1) => (v === null || v === undefined || !Number.isFinite(v) ? '–' : v.toFixed(d));
const pct = (v: number | null) => (v === null ? '–' : `${Math.round(v * 100)}%`);
const esc = (s: string) => s.replace(/\|/g, '\\|');
const sc = (b: BatchResult) => (b.error ? 0 : b.score!.score);
const mean = (xs: readonly number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);

function table(header: readonly string[], rows: readonly (readonly (string | number)[])[], align?: readonly ('l' | 'r')[]): string {
  const al = header.map((_, i) => ((align?.[i] ?? 'l') === 'r' ? '---:' : '---'));
  return [`| ${header.join(' | ')} |`, `| ${al.join(' | ')} |`, ...rows.map((r) => `| ${r.map((c) => (typeof c === 'number' ? String(c) : esc(c))).join(' | ')} |`)].join('\n');
}

function commentary(): Map<string, string> {
  const out = new Map<string, string>();
  const parts = commentaryText.split(/^<!-- @([a-z-]+) -->\s*$/m);
  for (let i = 1; i + 1 < parts.length; i += 2) out.set(parts[i], parts[i + 1].trim());
  return out;
}

const isDefaultConfig = (r: EvalOutput) =>
  r.config.k === 8 && r.config.n === APP_DEFAULTS.n && r.config.seed === 0x5eed && JSON.stringify(r.config.weights) === JSON.stringify(DEFAULT_WEIGHTS);

export function renderReport(r: EvalOutput, S: Summary): Report {
  const C = commentary();
  const note = (k: string) => (C.get(k) ? `${C.get(k)}\n\n` : '');
  const files: Record<string, string> = {};
  const seed = summarizeSeed(r.batches);
  const W = r.config.weights;
  const L: string[] = [];
  const push = (...s: string[]) => L.push(...s);

  push(
    '# Harmonic interest of the mkwavez generators',
    '',
    `Generated by \`npm run eval:harmonics\` (scripts/harmonics/): ${r.batches.length} batches of N = ${r.config.n} waveforms ` +
      `(${S.seed.length} Seed entries × default + ${r.config.k} random-parameter batches where the entry has anything to randomise, ` +
      `${S.mutate.length} mutations, ${S.breed.length} breed operators, ${S.shape.length} factory Shape chains, ${S.grid.length} grids), base seed ${r.config.seed}. ` +
      `Summary data: [${DATA_DIR}/](${DATA_DIR}/) (summary.json and one CSV per section, one row per item); the full per-batch dump is written locally to \`.harmonics/\`.`,
    '',
  );
  if (!isDefaultConfig(r)) push('> **Note:** this run does not use the default configuration; the hand-written commentary below was written against the default run and may not match the numbers.', '');

  push('## Summary', '', note('summary'));

  // ---- Method ----
  push(
    '## Method',
    '',
    "Every waveform is rendered by the app's own code — `seedTable()` for the Seed library (formula presets compiled by `src/browser/formulaEval.ts`, which is plain `new Function` and runs under Node unchanged), " +
      '`mutateBatch()`, `breedBatch()`, `applyChain()` and `gridRowTable()` — so each one leaves through `shape()` (DC removed, band-limited to 72 harmonics, phase-aligned, peak-normalised) exactly as the app adds it. ' +
      `Seed entries get their default batch (default params, seed ${r.config.seed}) plus ${r.config.k} batches with uniformly random params (on each slider's step grid; dropdowns uniformly) and a derived seed. ` +
      'Mutations, breeds and Shape chains run on reference waveforms (below). Metrics use the harmonic magnitudes 1…72 only.',
    '',
    '**References.** ' + Object.entries(r.references).map(([k, v]) => `*${k}* = ${v.how}`).join('; ') + '.',
    '',
    '**Per-waveform metrics** (dB re the strongest harmonic):',
    '',
    table(
      ['Metric', 'Definition'],
      [
        ['harmonics (sig)', `number of harmonics above ${SIG_DB} dB; *highest* = the highest of them`],
        ['centroid / spread', 'amplitude-weighted mean / standard deviation of the harmonic number'],
        ['flatness', 'geometric / arithmetic mean of the 72 harmonic powers (1 = white, 0 = a single harmonic)'],
        ['entropy', 'Shannon entropy of the normalised powers / ln 72'],
        ['slope', "least-squares fit of the significant harmonics' dB against log2 k, dB/octave (saw −6.0, triangle −12.0)"],
        ['odd/even', 'energy of odd harmonics ≥ 3 vs even harmonics (dB, ±60), and the even share of the energy above the fundamental'],
        ['irregularity', 'noise-like fine structure: RMS difference between neighbouring significant harmonics after removing a quadratic trend in log2 k, /√2 (saw 0, random magnitudes ≈ 5–6 dB)'],
        ['formants', `peaks in the spectral envelope (±1-harmonic max filter, 3-tap mean) with topographic prominence ≥ ${FORMANT_PROMINENCE_DB} dB`],
        ['h1', 'fundamental level (dB) and energy share'],
        ['divisor', `greatest common divisor of the harmonics above ${PITCH_DB} dB: 1 = pitched at the played note; g > 1 = every present harmonic is a multiple of g, so the waveform sounds g× higher (2 = an octave)`],
        ['crest', 'peak / RMS of the cycle'],
      ],
    ),
    '',
    '**Batch metrics** — distances are log-spectral distances (LSD): the RMS dB difference over the harmonics present (above ' +
      `${LSD_FLOOR_DB} dB) in either waveform, each spectrum floored at ${LSD_FLOOR_DB} dB. *path* = sum of consecutive LSDs; *net* = min(LSD(first, last), path); *straightness* = net / path (1 = one direction, → 0 = back and forth or a random walk); ` +
      `*step CV* = coefficient of variation of the step sizes; *duplicates* = consecutive pairs with LSD < ${DUP_LSD_DB} dB (of which *phase-only* = the cycles still differ by > ${Math.round(PHASE_ONLY_REL * 100)}% RMS); ` +
      '*static* = every waveform within the duplicate threshold of the first; *silent* = an all-zero waveform; *centroid range / monotonic* = range and |Spearman ρ| of the centroid along the batch.',
    '',
    `**Composite score** (0–100; scripts/harmonics/score.ts). A weighted geometric mean of six components in [0, 1], each floored at ${W.floor}, times penalties:`,
    '',
    '```',
    'score = 100 · exp(Σ wᵢ ln max(cᵢ, floor) / Σ wᵢ) · (1 − silentFrac) · (1 − dupPenalty · dupFrac)',
    `richness   = ½ clamp(log2(sig) / log2(${W.richCount})) + ½ clamp(entropy / ${W.richEntropy})                        w = ${W.richness}`,
    `balance    = (1 − clamp((flatness − ${W.flatLo}) / ${(W.flatHi - W.flatLo).toFixed(2)})) · (1 − ${W.irregPenalty} clamp((irregularity − ${W.irregLo}) / ${W.irregHi - W.irregLo}))  w = ${W.balance}`,
    `pitch      = (${W.h1Missing} + ${1 - W.h1Missing} clamp((h1 dB − (${W.h1Lo})) / ${W.h1Hi - W.h1Lo})) / divisor                       w = ${W.pitch}`,
    `motion     = 1 − exp(−travel / ${W.motionTau} dB),  travel = net + ${W.wander} · (path − net)               w = ${W.motion}`,
    `smoothness = 1 − ½ clamp(stepCV / 2)   (0.5 if path < 1 dB)                                     w = ${W.smoothness}`,
    `structure  = (½ + ½ min(formants, 2) / 2) · balance                                              w = ${W.structure}`,
    `dupPenalty = ${W.dupPenalty}`,
    '```',
    '',
    '*Motion* credits coherent sweeps: the net displacement from the first to the last waveform counts fully, the rest of the path (wandering back and forth, random walks) only by the wander fraction. ' +
      '*Pitch* keeps a waveform honest about the note it plays: a weak or missing fundamental costs up to half, and a common divisor g of the present harmonics (the waveform is really pitched g× higher) divides by g. ' +
      'Weights are adjustable (`--w.motion=1.5`, `--weights file.json`). Seed entries are ranked by *overall* = ½ default-batch score + ½ mean random-batch score (the default alone when there is nothing to randomise).',
    '',
    note('caveats'),
  );

  // ---- Seed ranking ----
  push('## Seed library ranking', '');
  push(
    table(
      ['#', 'Entry', 'Category', 'Overall', 'Default', 'Random mean (min–max)', 'Sig', 'Centroid', 'Slope', 'h1 dB', 'Div', 'Irreg', 'Path / net dB', 'Dup', 'Default flags'],
      S.seed.map((e) => [
        e.rank,
        e.label,
        e.category,
        f(e.overall),
        f(e.defaultScore),
        e.randomMean === null ? '– (nothing to randomise)' : `${f(e.randomMean)} (${f(e.minScore, 0)}–${f(e.maxScore, 0)})`,
        f(e.sig, 0),
        f(e.centroid),
        f(e.slope),
        f(e.h1Db, 0),
        f(e.divisor, 1),
        f(e.irregularity),
        `${f(e.pathLsd, 0)} / ${f(e.netLsd, 0)}`,
        pct(e.dupFrac),
        e.flags.replace(/ /g, ', '),
      ]),
      ['r', 'l', 'l', 'r', 'r', 'r', 'r', 'r', 'r', 'r', 'r', 'r', 'r', 'r', 'l'],
    ),
    '',
    'Sig, centroid, slope, h1, divisor, irregularity: means over the default batch; path / net and duplicates: the default batch.',
    '',
  );

  // ---- Highlights ----
  const top = S.seed.slice(0, 5);
  const bottom = S.seed.slice(-5);
  files[`${DATA_DIR}/centroid-top-bottom.svg`] = trajectoryPanels(
    'Spectral centroid along the default batch',
    'Top 5 (first row) and bottom 5 (second row) Seed entries by overall score',
    [...top, ...bottom].map((e) => ({ title: `${e.label.replace(/ \(.*\)$/, '')} · ${f(e.overall, 0)}`, values: e.centroids.map((c) => c ?? 0) })),
  );
  push(
    '## Highlights',
    '',
    `**Most interesting (overall):** ${top.map((e) => `${e.label} (${f(e.overall, 0)})`).join(', ')}.`,
    '',
    `**Least interesting:** ${bottom.map((e) => `${e.label} (${f(e.overall, 0)})`).join(', ')}.`,
    '',
    `![Centroid trajectories of the top and bottom entries](${DATA_DIR}/centroid-top-bottom.svg)`,
    '',
  );
  const moving = [...S.seed].filter((e) => e.netLsd !== null && (e.straightness ?? 0) >= 0.5).sort((a, b) => b.netLsd! - a.netLsd!);
  push(
    '**Best coherent sweeps** (default batches with straightness ≥ 0.5, by net displacement first → last): ' +
      moving
        .slice(0, 8)
        .map((e) => `${e.label} (travel ${f(e.travel, 0)} dB, net ${f(e.netLsd, 0)}, straightness ${f(e.straightness, 2)}, centroid ${f(e.centroids[0])}→${f(e.centroids[e.centroids.length - 1])})`)
        .join('; ') +
      '.',
    '',
  );
  const walks = S.seed.filter((e) => (e.pathLsd ?? 0) > 20 && (e.straightness ?? 1) < 0.25);
  if (walks.length) push(`**Random walks** (default path > 20 dB, straightness < 0.25): ${walks.map((e) => `${e.label} (path ${f(e.pathLsd, 0)}, net ${f(e.netLsd, 0)})`).join(', ')}.`, '');
  const barely = S.seed.filter((e) => !e.flags.includes('static') && (e.travel ?? 0) < 8);
  if (barely.length) push(`**Default batches that barely move** (travel < 8 dB, not static): ${barely.map((e) => `${e.label} (${f(e.travel, 1)} dB)`).join(', ')}.`, '');
  const pitchy = S.seed.filter((e) => e.flags.includes('no-fundamental') || e.flags.includes('pitch-shifted'));
  if (pitchy.length) push(`**Missing fundamental or pitch-shifted** (default batch): ${pitchy.map((e) => `${e.label} (h1 ${f(e.h1Db, 0)} dB, divisor ${f(e.divisor, 1)})`).join(', ')}.`, '');
  const under = S.seed.filter((e) => e.randomMean !== null && e.randomMean - e.defaultScore! > 8);
  const dead = S.seed.filter((e) => e.randomMean !== null && e.defaultScore! - e.randomMean > 15);
  if (under.length) push(`**Defaults that undersell the parameter space** (random mean − default > 8): ${under.map((e) => `${e.label} (${f(e.defaultScore, 0)} vs ${f(e.randomMean, 0)})`).join(', ')}.`, '');
  if (dead.length) push(`**Parameter spaces with many dead corners** (default − random mean > 15): ${dead.map((e) => `${e.label} (${f(e.defaultScore, 0)} vs ${f(e.randomMean, 0)}; worst ${f(e.minScore, 0)})`).join(', ')}.`, '');

  push(
    '### Problem cases (Seed)',
    '',
    'Flags: *silent* (an all-zero waveform), *static* (all waveforms ≈ the first), *duplicates* (≥ 50% consecutive near-duplicates), *phase-only*, *flat* (mean flatness > 0.5), *sine-like* (mean ≤ 1.5 significant harmonics), ' +
      `*no-fundamental* (mean h1 < −40 dB), *pitch-shifted* (mean divisor ≥ 1.5), *error*. Settings reproduce the batch (N = ${r.config.n}).`,
    '',
  );
  const probRows: (string | number)[][] = [];
  for (const e of seed) {
    for (const b of [e.default, ...e.randoms]) {
      const fl = flagsOf(b).filter((x) => x !== 'erratic');
      if (!fl.length) continue;
      if (e.mode === 'basic' && fl.includes('static')) continue; // static by design
      probRows.push([e.label, b.variant, fl.join(', '), f(sc(b), 0), b.error ?? seedSettings(b)]);
    }
  }
  push(
    probRows.length ? table(['Entry', 'Batch', 'Flags', 'Score', 'Settings'], probRows, ['l', 'l', 'l', 'r', 'l']) : '_None._',
    '',
    'Not listed: the four basic waves (Sine, Triangle, Saw, Square), which are a single waveform by design.',
    '',
  );

  // ---- Per category ----
  push('## Observations by category', '', '### Seed modes and formula presets', '', note('seed'));
  const cats = new Map<string, Summary['seed']>();
  for (const e of S.seed) cats.set(e.category, [...(cats.get(e.category) ?? []), e]);
  push(
    table(
      ['Category', 'Entries', 'Mean overall', 'Best', 'Worst'],
      [...cats.entries()]
        .map(([c, es]) => ({ c, es, m: mean(es.map((e) => e.overall ?? 0)) }))
        .sort((a, b) => b.m - a.m)
        .map(({ c, es, m }) => [c, es.length, f(m), `${es[0].label} (${f(es[0].overall, 0)})`, `${es[es.length - 1].label} (${f(es[es.length - 1].overall, 0)})`]),
      ['l', 'r', 'r', 'l', 'l'],
    ),
    '',
  );
  const formulas = S.seed.filter((e) => e.mode === 'formula');
  const gens = S.seed.filter((e) => e.mode !== 'formula');
  const gensNoBasic = gens.filter((e) => e.mode !== 'basic');
  push(
    `Formula presets (${formulas.length}): mean overall ${f(mean(formulas.map((e) => e.overall ?? 0)))}, mean default ${f(mean(formulas.map((e) => e.defaultScore ?? 0)))}; ` +
      `generator / parameter-mode entries (${gens.length}): ${f(mean(gens.map((e) => e.overall ?? 0)))} overall; without the four basic waves, mean default ${f(mean(gensNoBasic.map((e) => e.defaultScore ?? 0)))}.`,
    '',
  );

  // Mutations.
  push('### Mutate', '', note('mutate'));
  files[`${DATA_DIR}/mutation-effect.svg`] = barChart(
    `Mutation effect at the default amount (${APP_DEFAULTS.mutateAmount})`,
    'LSD (dB) from the source to the result, mean of saw / formant / noisy; dashed line 1 dB',
    S.mutate
      .map((m) => ({ label: m.label, value: mean([m.effectSaw, m.effectFormant, m.effectNoisy].map((v) => v ?? 0)) }))
      .sort((a, b) => b.value - a.value),
    'dB',
    { value: 1, label: '1 dB' },
  );
  push(
    `Each mutation × {saw, formant, noisy} × amounts {${r.config.amounts.join(', ')}} × {${r.config.modes.join(', ')}}, N = ${r.config.n}, one seed per mutation. ` +
      "*Effect* = LSD from the source to the batch's last waveform (= the amount itself for lin / log).",
    '',
    table(
      ['Mutation', 'Group', 'Mean score', `Effect @ ${APP_DEFAULTS.mutateAmount} lin (saw / formant / noisy, dB)`, 'Effect @ 1 (mean)', 'Score lin / log / chain', 'Dup', 'Notes'],
      S.mutate.map((m) => [
        m.label,
        m.group,
        f(m.meanScore),
        `${f(m.effectSaw)} / ${f(m.effectFormant)} / ${f(m.effectNoisy)}`,
        f(m.effectFull),
        `${f(m.scoreLin, 0)} / ${f(m.scoreLog, 0)} / ${f(m.scoreChain, 0)}`,
        pct(m.dupFrac),
        m.notes,
      ]),
      ['l', 'l', 'r', 'r', 'r', 'r', 'r', 'l'],
    ),
    '',
    `![Mutation effect at the default amount](${DATA_DIR}/mutation-effect.svg)`,
    '',
  );

  // Breed.
  push('### Breed', '', note('breed'));
  const sets = [...new Set(r.batches.filter((b) => b.section === 'breed').map((b) => (b.settings.parents as string[]).join('+')))];
  push(
    `Each operator × parent sets {${sets.join(', ')}} × {sweep bias ${APP_DEFAULTS.breedBias}, sweep bias 1, generation bias ${APP_DEFAULTS.breedBias}}, walk ${APP_DEFAULTS.breedWalk}, rate ${APP_DEFAULTS.breedRate}, N = ${r.config.n}. ` +
      '*Effect A / B* = LSD from parent A / parent B (the second parent) to the last child of the bias-0.5 sweep.',
    '',
    table(
      ['Operator', 'Seeded', 'Mean score', 'Sweep 0.5', 'Sweep 1', 'Gen 0.5', 'Effect A / B @ sweep 0.5 (dB)', 'Dup', 'Phase-only'],
      S.breed.map((b) => [b.label, b.seeded ? 'yes' : 'no', f(b.meanScore), f(b.sweepHalf, 0), f(b.sweepFull, 0), f(b.genHalf, 0), `${f(b.effectA)} / ${f(b.effectB)}`, pct(b.dupFrac), pct(b.phaseOnlyFrac)]),
      ['l', 'l', 'r', 'r', 'r', 'r', 'r', 'r', 'r'],
    ),
    '',
  );

  // Shape.
  push('### Shape chains', '', note('shape'));
  push(
    `Each factory chain on {saw, formant, noisy, sine} at batch positions 0…${r.config.n - 1} of ${r.config.n}. *Effect* = LSD from the source to the first or the last waveform, whichever is larger (a sweep may start at amount 0); *path* = the batch's motion (0 for chains that neither sweep nor vary the seed).`,
    '',
    table(
      ['Chain', 'Kind', 'Effect saw / formant / noisy / sine (dB)', 'Sig on saw', 'Centroid on saw', 'Path (mean dB)', 'Mean score'],
      S.shape.map((s) => [s.label, s.kind, [s.effectSaw, s.effectFormant, s.effectNoisy, s.effectSine].map((v) => f(v)).join(' / '), f(s.sigSaw, 0), f(s.centroidSaw), f(s.pathLsd), f(s.meanScore)]),
      ['l', 'l', 'r', 'r', 'r', 'r', 'r'],
    ),
    '',
    'For reference: saw has 72 significant harmonics and centroid 14.8.',
    '',
  );

  // Grid.
  if (S.grid.length) {
    push(
      '### Grid',
      '',
      note('grid'),
      `Generate → Grid with Seed default batches as columns and a row operation down each column (${r.config.n} × ${r.config.n}; row 1 = the columns when \`row1Fits\`). Mean consecutive LSD along X (between columns) and Y (down the rows).`,
      '',
      table(
        ['Columns', 'Rows', 'Row 1 = columns', 'Step X (dB)', 'Step Y (dB)', 'Dup X', 'Dup Y', 'Score X', 'Score Y'],
        S.grid.map((g) => [g.columns, g.rows, g.row1 ? 'yes' : 'no', f(g.stepX), f(g.stepY), pct(g.dupX), pct(g.dupY), f(g.scoreX, 0), f(g.scoreY, 0)]),
        ['l', 'l', 'l', 'r', 'r', 'r', 'r', 'r', 'r'],
      ),
      '',
    );
  }

  push('## Recommendations', '', note('recommendations'));

  push(
    '## Appendix',
    '',
    '### Re-running',
    '',
    '```sh',
    'npm run eval:harmonics                       # everything, default configuration (a few seconds; timings on stdout)',
    'npm run eval:harmonics -- --k 16 --seed 7    # more random batches, another seed',
    'npm run eval:harmonics -- --w.motion=2       # re-weight the score',
    'npm run eval:harmonics -- --only karplus     # one item, full dump only',
    '```',
    '',
    '### Notes',
    '',
    ...r.notes.map((n) => `- ${n}`),
    '',
    '### Files',
    '',
    `- \`${DATA_DIR}/summary.json\` — configuration, references and one rounded row per item and section (Seed rows include the default batch's centroid trajectory and the worst batch's settings).`,
    `- \`${DATA_DIR}/seed.csv\`, \`mutate.csv\`, \`breed.csv\`, \`shape.csv\`, \`grid.csv\` — the same rows as CSV.`,
    '- `.harmonics/results.json` and `.harmonics/*-batches.csv` (local, not committed) — every batch with its settings, all metrics, score parts and timings.',
    '',
    `Harmonics evaluated: 1…${K}.`,
    '',
  );
  return { md: L.join('\n').replace(/\n{3,}/g, '\n\n'), files };
}
